"""Convert a photo into a 1-bit 800x480 bitmap header for the e-paper display.

Usage: .venv/bin/python tools/convert.py <photo> [--landscape]

Portrait photos (default) are cropped to 480x800 and rotated onto the
landscape panel, so the frame is stood upright. Writes include/photo.h
and images/preview.png (what the screen will show).
"""
import sys
from pathlib import Path

from PIL import Image, ImageOps

W, H = 800, 480  # native panel size
ROOT = Path(__file__).resolve().parent.parent

src = Path(sys.argv[1])
landscape = "--landscape" in sys.argv

img = ImageOps.exif_transpose(Image.open(src)).convert("L")
img = ImageOps.fit(img, (W, H) if landscape else (H, W), Image.LANCZOS)
img = ImageOps.autocontrast(img, cutoff=1)
bw = img.convert("1")  # Floyd-Steinberg dithering
bw.save(ROOT / "images" / "preview.png")
if not landscape:
    bw = bw.rotate(-90, expand=True)  # photo top -> right edge of panel

# 1 bit per pixel, MSB first, rows padded to bytes; bit set = black pixel
data = bytes(b ^ 0xFF for b in bw.tobytes())

lines = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
(ROOT / "include" / "photo.h").write_text(
    f"// Generated by tools/convert.py from {src.name} — do not edit\n"
    "#pragma once\n#include <pgmspace.h>\n\n"
    f"#define PHOTO_WIDTH {W}\n#define PHOTO_HEIGHT {H}\n\n"
    "const unsigned char photo[] PROGMEM = {\n  " + ",\n  ".join(lines) + "\n};\n"
)
print(f"Wrote include/photo.h ({len(data)} bytes) and images/preview.png")
